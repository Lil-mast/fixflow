"""Identifier generation and canonical request hashing.

``reportId`` and ``uploadId`` are UUIDv4 values generated by the browser. ``publicRef``
is an 80-bit Crockford Base32 capability, formatted for humans. ``eventId`` is a ULID so
events sort by time even when two share a millisecond.
"""

from __future__ import annotations

import hashlib
import json
import re
import secrets
import time
import uuid
from typing import Any

CROCKFORD_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

UUID4_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
    re.IGNORECASE,
)
PUBLIC_REF_BODY_RE = re.compile(r"^[0-9A-HJKMNP-TV-Z]{16}$")


def is_uuid4(value: Any) -> bool:
    return isinstance(value, str) and UUID4_RE.fullmatch(value) is not None


def new_uuid4() -> str:
    return str(uuid.uuid4())


def _base32(data: bytes, length: int) -> str:
    """Encode bytes as Crockford Base32, right-padding the final group."""

    buffer = 0
    bits = 0
    output: list[str] = []
    for byte in data:
        buffer = (buffer << 8) | byte
        bits += 8
        while bits >= 5:
            bits -= 5
            output.append(CROCKFORD_ALPHABET[(buffer >> bits) & 0x1F])
    if bits:
        output.append(CROCKFORD_ALPHABET[(buffer << (5 - bits)) & 0x1F])
    return "".join(output)[:length]


def new_public_ref() -> str:
    body = _base32(secrets.token_bytes(10), 16)
    return "FF-" + "-".join(body[index : index + 4] for index in range(0, 16, 4))


def normalize_public_ref(value: Any) -> str | None:
    """Normalize a public reference, returning ``None`` when it is malformed."""

    if not isinstance(value, str):
        return None
    compact = value.strip().upper().replace("-", "")
    if not compact.startswith("FF"):
        return None
    body = compact[2:]
    if len(body) != 16 or PUBLIC_REF_BODY_RE.fullmatch(body) is None:
        return None
    return "FF-" + "-".join(body[index : index + 4] for index in range(0, 16, 4))


def _encode_timestamp(timestamp_ms: int) -> str:
    chars = []
    for _ in range(10):
        chars.append(CROCKFORD_ALPHABET[timestamp_ms & 0x1F])
        timestamp_ms >>= 5
    return "".join(reversed(chars))


def new_ulid(timestamp_ms: int | None = None) -> str:
    moment = timestamp_ms if timestamp_ms is not None else int(time.time() * 1000)
    return _encode_timestamp(moment) + _base32(secrets.token_bytes(10), 16)


def canonical_json(payload: dict[str, Any]) -> str:
    return json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    )


def sha256_hex(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()
